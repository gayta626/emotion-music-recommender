import { useEffect, useState } from 'react';
import { Link, useNavigate, useParams } from 'react-router-dom';
import api from '../api';
import { useAuth } from '../contexts/authContext';
import UserAvatar from '../components/UserAvatar';
import UserActions from '../components/admin/UserActions';
import { AdminTabs } from '../components/admin/AdminLayout';
import { lastActive, pct } from '../components/admin/adminMeta';
import { EMOTIONS, OUTCOMES } from '../components/stats/statsMeta';

// Dữ liệu riêng của 1 người (/admin/users/:id, chỉ admin): tóm tắt, gu, bài nghe nhiều, điểm sở thích AI học được,
// playlist, bài đã thích, nhật ký quét / nghe gần nhất. Số liệu từ GET /admin/users/:id.
const LABEL = Object.fromEntries(EMOTIONS.map((e) => [e.key, e.label]));
const ACTION_LABEL = { suggested: 'Scan / mood pick', ...Object.fromEntries(OUTCOMES.map((o) => [o.key, o.label])) };

const dateTime = (iso) => new Date(iso).toLocaleString('en-GB', { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' });
const joined = (iso) => new Date(iso).toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' });
const songName = (s) => (s.title ? <>{s.title}{s.artist && <small> · {s.artist}</small>}</> : <span className="mood-muted">Deleted song</span>);

const Empty = ({ children }) => <p className="mood-muted chart-empty">{children}</p>;

const AdminUserPage = () => {
    const { id } = useParams();
    const { user: me } = useAuth();
    const navigate = useNavigate();
    const [data, setData] = useState(null);
    const [error, setError] = useState('');
    const [openList, setOpenList] = useState(null);   // id playlist đang mở

    useEffect(() => {
        let alive = true;
        api.get(`/admin/users/${id}`)
            .then((res) => { if (alive) { setData(res.data); setError(''); } })
            .catch((err) => { if (alive) setError(err.response?.data?.error || "Couldn't load this account."); });
        return () => { alive = false; };
    }, [id]);

    const back = <Link className="admin-back" to="/admin/users">‹ All users</Link>;

    if (!data || String(data.user.id) !== id) {
        return (
            <div className="mood-page stats-page admin-page admin-manage">
                <AdminTabs />
                {back}
                {error ? <p className="stats-error">{error}</p> : <p className="mood-muted">Loading…</p>}
            </div>
        );
    }

    const { user, summary, taste } = data;
    const maxScan = Math.max(1, ...Object.values(summary.scansByEmotion));

    return (
        <div className="mood-page stats-page admin-page admin-manage">
            <AdminTabs />
            {back}
            <header className="user-hero stats-card">
                <UserAvatar username={user.username} size={64} />
                <div className="uh-text">
                    <h1>
                        {user.username}
                        <span className={`role-tag ${user.role}`}>{user.role === 'admin' ? 'Admin' : 'User'}</span>
                        <span className={`state-tag ${user.locked ? 'locked' : 'active'}`}>{user.locked ? 'Locked' : 'Active'}</span>
                        {user.sample && <span className="sample-tag" title="Generated by npm run seed-demo, not a real person">sample</span>}
                    </h1>
                    <p className="mood-muted">
                        Joined {joined(user.createdAt)} · {user.surveyDone ? 'Did the taste survey' : 'No taste survey yet'}
                        {user.locked && ` · Locked ${lastActive(user.lockedAt).toLowerCase()}`}
                    </p>
                </div>
                <UserActions
                    user={user}
                    meId={me?.id}
                    onChange={(u) => setData((d) => ({ ...d, user: { ...d.user, ...u } }))}
                    onDeleted={() => navigate('/admin/users', { replace: true })}
                />
            </header>
            <p className="admin-privacy">Private data of one person. Open it only to help them or to check the system.</p>

            <section className="user-stats" aria-label="Summary">
                <div className="stats-card"><span>Scans</span><b>{summary.scans}</b></div>
                <div className="stats-card"><span>Listens</span><b>{summary.listens}</b></div>
                <div className="stats-card"><span>Played to the end</span><b>{summary.completion == null ? '—' : pct(summary.completion)}</b></div>
                <div className="stats-card"><span>Playlists</span><b>{data.playlists.length}</b></div>
                <div className="stats-card"><span>Liked songs</span><b>{data.liked.length}</b></div>
            </section>

            <div className="stats-pair">
                <section className="stats-card">
                    <div className="chart-top"><h3>Scans by mood</h3></div>
                    {!summary.scans ? <Empty>No scans yet.</Empty> : (
                        <ul className="mood-bars">
                            {EMOTIONS.map((e) => {
                                const n = summary.scansByEmotion[e.key] || 0;
                                return (
                                    <li key={e.key} className={e.key}>
                                        <span>{e.label}</span>
                                        <span className="bar" aria-hidden="true"><i style={{ width: `${(n / maxScan) * 100}%` }} /></span>
                                        <b>{n}</b>
                                    </li>
                                );
                            })}
                        </ul>
                    )}
                    <ul className="outcome-list">
                        {OUTCOMES.map((o) => (
                            <li key={o.key} className={`out-${o.key}`}><span className="swatch" aria-hidden="true" />{o.label}: <b>{summary.outcomes[o.key]}</b></li>
                        ))}
                    </ul>
                </section>
                <section className="stats-card">
                    <div className="chart-top"><h3>Music taste</h3></div>
                    <p className="stats-note">From the taste survey / Settings. NYX adds a bonus to these when picking songs.</p>
                    <div className="taste-group">
                        <span>Genres</span>
                        <div className="chips">{taste.genres.length ? taste.genres.map((g) => <span key={g} className="chip">{g}</span>) : <span className="mood-muted">None</span>}</div>
                    </div>
                    <div className="taste-group">
                        <span>Artists</span>
                        <div className="chips">{taste.artists.length ? taste.artists.map((a) => <span key={a} className="chip">{a}</span>) : <span className="mood-muted">None</span>}</div>
                    </div>
                </section>
            </div>

            <div className="stats-pair">
                <section className="stats-card">
                    <div className="chart-top"><h3>Most played</h3></div>
                    {!data.topSongs.length ? <Empty>Nothing played yet.</Empty> : (
                        <div className="mood-table-wrap">
                            <table className="mood-table">
                                <thead><tr><th>Song</th><th>Plays</th><th>Last played</th></tr></thead>
                                <tbody>
                                    {data.topSongs.map((s) => (
                                        <tr key={s.id}><td className="song-cell">{songName(s)}</td><td>{s.plays}</td><td>{lastActive(s.lastPlayed)}</td></tr>
                                    ))}
                                </tbody>
                            </table>
                        </div>
                    )}
                </section>
                <section className="stats-card">
                    <div className="chart-top"><h3>What NYX learned</h3></div>
                    <p className="stats-note">Highest preference scores per mood (+ when played to the end, − when skipped).</p>
                    {!data.preferences.length ? <Empty>No scores yet.</Empty> : (
                        <div className="mood-table-wrap">
                            <table className="mood-table">
                                <thead><tr><th>Song</th><th>Mood</th><th>Score</th></tr></thead>
                                <tbody>
                                    {data.preferences.map((p) => (
                                        <tr key={`${p.id}-${p.emotion}`}><td className="song-cell">{songName(p)}</td><td>{LABEL[p.emotion] || p.emotion}</td><td>{p.score.toFixed(1)}</td></tr>
                                    ))}
                                </tbody>
                            </table>
                        </div>
                    )}
                </section>
            </div>

            <div className="stats-pair">
                <section className="stats-card">
                    <div className="chart-top"><h3>Playlists</h3></div>
                    {!data.playlists.length ? <Empty>No playlists.</Empty> : (
                        <ul className="pl-list">
                            {data.playlists.map((p) => (
                                <li key={p.id}>
                                    <button aria-expanded={openList === p.id} onClick={() => setOpenList((v) => (v === p.id ? null : p.id))}>
                                        <b>{p.name}</b><span>{p.songs.length} song{p.songs.length === 1 ? '' : 's'}</span>
                                    </button>
                                    {openList === p.id && (
                                        p.songs.length ? (
                                            <ol>{p.songs.map((s) => <li key={s.id}>{songName(s)}</li>)}</ol>
                                        ) : <Empty>Empty playlist.</Empty>
                                    )}
                                </li>
                            ))}
                        </ul>
                    )}
                </section>
                <section className="stats-card">
                    <div className="chart-top"><h3>Liked songs</h3></div>
                    {!data.liked.length ? <Empty>No liked songs.</Empty> : (
                        <ol className="liked-list">
                            {data.liked.map((s) => <li key={s.id}><span className="song-cell">{songName(s)}</span><small>{lastActive(s.likedAt)}</small></li>)}
                        </ol>
                    )}
                </section>
            </div>

            <section className="stats-card">
                <div className="chart-top"><h3>Recent activity</h3></div>
                <p className="stats-note">Last {data.historyLimit} scans and listening results, newest first. Confidence is empty for manual mood picks.</p>
                {!data.history.length ? <Empty>No activity yet.</Empty> : (
                    <div className="mood-table-wrap">
                        <table className="mood-table history-table">
                            <thead><tr><th>When</th><th>Event</th><th>Mood</th><th>AI confidence</th><th>Song</th></tr></thead>
                            <tbody>
                                {data.history.map((h) => (
                                    <tr key={h.id}>
                                        <td>{dateTime(h.createdAt)}</td>
                                        <td>{ACTION_LABEL[h.action] || h.action}</td>
                                        <td>{LABEL[h.emotion] || h.emotion}</td>
                                        <td>{h.confidence == null ? '—' : pct(h.confidence)}</td>
                                        <td className="song-cell">{h.songId || h.title ? songName(h) : '—'}</td>
                                    </tr>
                                ))}
                            </tbody>
                        </table>
                    </div>
                )}
            </section>
        </div>
    );
};

export default AdminUserPage;
