import { Link } from 'react-router-dom';
import StatsCard from '../stats/StatsCard';
import UserAvatar from '../UserAvatar';
import { StatusPill } from './HealthTile';
import { STATUS, lastActive, pct } from './adminMeta';

// 1 ô tỉ lệ: chấm + chữ mức (đọc được khi không thấy màu) + số; chưa đủ mẫu -> "—"
const RateCell = ({ value, level }) => (
    <td className={`rate-cell s-${level}`}>
        {value == null ? '—' : (
            <>
                <span className="rate-dot" aria-hidden="true" />
                <span className="sr-only">{STATUS[level].label}: </span>
                {pct(value)}
            </>
        )}
    </td>
);

// Bảng theo từng người dùng: chỉ số tốt / xấu của cả hệ thống đến từ ai (vd 1 người ngồi chỗ tối -> AI kém chắc chắn)
const UserTable = ({ users, minSamples }) => (
    <StatsCard
        className="user-card"
        title="By user"
        note={`Where problems come from: one person's lighting or camera can pull the whole system down. Rates need at least ${minSamples} samples per person.`}
    >
        {!users.length ? (
            <p className="mood-muted chart-empty">Nobody used the mood loop in this period.</p>
        ) : (
            <div className="mood-table-wrap">
                <table className="mood-table user-table">
                    <thead>
                        <tr>
                            <th>User</th>
                            <th>Scans</th>
                            <th>Camera</th>
                            <th>AI confidence</th>
                            <th>Unsure</th>
                            <th>Corrected</th>
                            <th>Finished</th>
                            <th>Last active</th>
                            <th>Status</th>
                        </tr>
                    </thead>
                    <tbody>
                        {users.map((u) => (
                            <tr key={u.id}>
                                <td>
                                    <Link className="user-name" to={`/admin/users/${u.id}`}>
                                        <UserAvatar username={u.username} size={28} />
                                        {u.username}
                                        {u.sample && <span className="sample-tag" title="Generated by npm run seed-demo, not a real person">sample</span>}
                                    </Link>
                                </td>
                                <td>{u.scans}</td>
                                <td>{u.cam}</td>
                                <RateCell value={u.confidence} level={u.levels.confidence} />
                                <RateCell value={u.unsure} level={u.levels.unsure} />
                                <RateCell value={u.corrections} level={u.levels.corrections} />
                                <RateCell value={u.completion} level={u.levels.completion} />
                                <td>{lastActive(u.lastAt)}</td>
                                <td><StatusPill status={u.status} /></td>
                            </tr>
                        ))}
                    </tbody>
                </table>
            </div>
        )}
    </StatsCard>
);

export default UserTable;
